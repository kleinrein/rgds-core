/* Native build step: the kernels' right answers, for the ROM to check the emulated ones against. */
#include <stdio.h>
#include "kernels.h"
int main(void) {
    puts("/* Generated by tools/build_impeccable.py from kernels.c run natively. */");
    printf("static const u32 GOLDEN[KERNELS][4] = {\n");
    for (int k = 0; k < KERNELS; ++k) {
        printf("    {");
        for (int s = 0; s < 4; ++s) printf("0x%08Xu, ", kernel_arm(k, 0x1000193u * (u32)(s + 1)));
        printf("},\n");
    }
    puts("};");
    return 0;
}
