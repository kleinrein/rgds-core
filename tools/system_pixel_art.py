"""The system pixel art: one 16 x 16 glyph per stock Anbernic RG DS Linux system.

`#` is ink, `+` a half-tone of the same ink (screens, panels), `.` empty.
The grid is 16 x 16 so a system still reads as its hardware at the sizes the
launcher draws it (48, 64 and 72 px are whole multiples of 16).

Drawing rules, so the set stays one family:

* The silhouette is the real hardware's silhouette: a console's shape, a
  handheld's shape, an arcade cabinet's shape.
* A body is drawn as an outline of `#` with `+` panels and `+` screens;
  details (a D-pad, buttons, a cartridge slot) are solid `#` marks.
* One object per glyph, centred, with a one-cell margin.
* Nothing that needs a legend to be understood, and no letterforms.

The brief below says what every glyph has to be recognisable as.
`tools/build_system_icons.py` turns this table into the launcher's masks, the
SVG drawings and the review sheet, so all three can never drift apart.
"""

